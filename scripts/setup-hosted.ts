/**
 * Guided hosted-mode deploy to Fly.io: `npm run setup:hosted`
 *
 *   1. checks the Fly CLI is installed and signed in; asks for Plaid keys if .env has none
 *      (so hosted-only installs never need the local wizard, a compiler or a local build)
 *   2. asks for an app name, region and display name; writes fly.toml from the template
 *   3. creates the app and its volume (skips what already exists)
 *   4. generates TOKEN_ENCRYPTION_KEY (kept in .env too, for migrating banks later),
 *      asks for a passphrase with hidden input, and sets every secret without a shell
 *   5. deploys, waits for /health, and prints the URLs to connect Claude
 *
 * Re-runnable: existing app, volume and fly.toml are reused; secrets are re-set.
 */
import fs from "node:fs";
import path from "node:path";
import { createHash, randomBytes, randomInt } from "node:crypto";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { PlaidClient, PlaidEnvironment } from "plaid";
import { ask, askHidden, collectPlaidKeys, fail, mergeEnv, ok, parseEnv, run, say, warn } from "./setup.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ENV_PATH = path.join(ROOT, ".env");
const FLY_TOML = path.join(ROOT, "fly.toml");
const FLY_TEMPLATE = path.join(ROOT, "fly.example.toml");
const APP_NAME_RE = /^[a-z0-9][a-z0-9-]{1,28}[a-z0-9]$/;
const REGION_RE = /^[a-z]{3}$/;
const MIN_PASSPHRASE = 12;
const WORDS = ["able","acid","aged","also","area","army","away","baby","back","ball","band","bank","base","bath","bear","beat","been","beer","bell","belt","bend","bent","best","bird","blow","blue","boat","body","bolt","bone","book","boot","born","boss","both","bowl","bulk","burn","bush","busy","cake","calm","came","camp","card","care","cart","case","cash","cast","cave","cell","chat","chef","chip","city","clay","clip","club","coal","coat","code","coin","cold","come","cook","cool","copy","core","corn","cost","crew","crop","cure","dark","data","date","dawn","days","dead","deal","dear","debt","deck","deep","deer","desk","dial","diet","dirt","dish","disk","dock","does","dome","done","door","dose","dove","down","draw","drop","drum","dual","duck","dust","duty","each","earn","ease","east","easy","edge","else","even","ever","exit","face","fact","fade","fail","fair","fall","fame","farm","fast","fate","fear","feed","feel","fell","file","fill","film","find","fine","fire","firm","fish","five","flag","flat","flow","fold","folk","food","foot","ford","form","fort","four","free","from","fuel","full","fund","gain","game","gate","gave","gear","gift","girl","give","glad","glow","goal","goat","gold","golf","gone","good","gray","grew","grid","grip","grow","gulf","hair","half","hall","hand","hang","hard","harm","hawk","head","hear","heat","held","help","herb","hero","hide","high","hill","hint","hire","hold","hole","holy","home","hope","horn","host","hour","huge","hunt","idea","inch","iron","item","jade","jazz","join","joke","jump","jury","just","keen","keep","kept","kick","kind","king","kite","knee","knew","knot","lack","lake","lamp","land","lane","last","late","lawn","lead","leaf","lean","left","lend","lens","less","life","lift","lime","line","link","lion","list","live","load","loan","lock","loft"];
/** Five random words from a 256-word list: 40 bits of entropy, easy to type on a phone. */
export function generatePassphrase(count = 5): string {
  return Array.from({ length: count }, () => WORDS[randomInt(WORDS.length)]).join("-");
}

/** Fill the template with the chosen values. Pure, for tests. */
export function renderFlyToml(template: string, v: { app: string; region: string; appName: string; plaidEnv: "production" | "sandbox" }): string {
  return template
    .replace(/^# Copy to fly\.toml.*$/m, `# Generated by \`npm run setup:hosted\`; git-ignored. Edit freely and run \`fly deploy -a ${v.app} --ha=false\`.`)
    .replace(/^app = "<app>"/m, `app = "${v.app}"`)
    .replace(/^primary_region = "<region>".*$/m, `primary_region = "${v.region}"`)
    .replace(/PUBLIC_URL = "https:\/\/<app>\.fly\.dev"/, `PUBLIC_URL = "https://${v.app}.fly.dev"`)
    .replace(/^(\s*)APP_NAME = ".*?"(.*)$/m, `$1APP_NAME = "${v.appName.replace(/"/g, "")}"$2`)
    .replace(/^(\s*)PLAID_ENV = ".*?"(.*)$/m, `$1PLAID_ENV = "${v.plaidEnv}"$2`);
}

/** Read the app name back out of an existing fly.toml. Pure, for tests. */
export function appFromFlyToml(toml: string): string | null {
  const m = /^app = "([^"]+)"/m.exec(toml);
  return m && m[1] !== "<app>" ? m[1] : null;
}

function fly(args: string[], opts: { quiet?: boolean } = {}): { ok: boolean; out: string } {
  const r = spawnSync("fly", args, { cwd: ROOT, encoding: "utf8", stdio: opts.quiet ? ["ignore", "pipe", "pipe"] : ["inherit", "pipe", "pipe"] });
  return { ok: r.status === 0, out: `${r.stdout ?? ""}${r.stderr ?? ""}` };
}

async function main() {
  say("\nplaid-finance-mcp hosted setup (Fly.io)\n");
  if (!process.stdin.isTTY) fail("Run this in an interactive terminal.");

  // 1. Prerequisites
  if (!fly(["version"], { quiet: true }).ok) fail("The Fly CLI is not installed. See https://fly.io/docs/flyctl/install/ then run `fly auth login`.");
  ok("Fly CLI installed");
  if (!fly(["auth", "whoami"], { quiet: true }).ok) fail("Not signed in to Fly. Run `fly auth login` and try again.");
  ok("signed in to Fly");
  say("\n  Which Plaid environment should this server use?");
  say("    production  real banks, real money. Needs Plaid production access and a production secret.");
  say("    sandbox     Plaid's fake banks (sign in with user_good / pass_good). Free; good for a first try.\n");
  let plaidEnv: "production" | "sandbox" = "production";
  for (;;) {
    const a = (await ask("  Type production or sandbox [production]: ")).toLowerCase();
    if (a === "" || a === "production" || a === "p") break;
    if (a === "sandbox" || a === "s") {
      plaidEnv = "sandbox";
      break;
    }
    warn("Please type production or sandbox.");
  }

  let env = fs.existsSync(ENV_PATH) ? parseEnv(fs.readFileSync(ENV_PATH, "utf8")) : {};
  const secretOf = (e: Record<string, string>) => (plaidEnv === "production" ? e.PLAID_SECRET_PRODUCTION || e.PLAID_SECRET : e.PLAID_SECRET_SANDBOX || e.PLAID_SECRET);
  if (!env.PLAID_CLIENT_ID || !secretOf(env)) {
    say(`\n  No ${plaidEnv} Plaid keys in .env yet; let's add them. (Running the local wizard first is not required.)`);
    env = await collectPlaidKeys(plaidEnv);
  }
  // One cheap read-only call proves the keys work for this environment before anything is created.
  let secret = "";
  for (let attempt = 1; ; attempt++) {
    secret = secretOf(env) ?? "";
    if (!env.PLAID_CLIENT_ID || !secret) fail(`PLAID_CLIENT_ID and a ${plaidEnv} secret are required.`);
    try {
      const client = new PlaidClient({ environment: plaidEnv === "production" ? PlaidEnvironment.Production : PlaidEnvironment.Sandbox, clientId: env.PLAID_CLIENT_ID, secret });
      await client.institutions.getById({ institution_id: "ins_109508", country_codes: ["US"] });
      ok(`Plaid keys verified for ${plaidEnv}`);
      break;
    } catch (e) {
      const code = (e as { body?: { error_code?: string } })?.body?.error_code;
      warn(`Plaid rejected the keys for ${plaidEnv}${code ? ` (${code})` : ""}. They are at https://dashboard.plaid.com/developers/keys.`);
      if (attempt >= 3 || (await ask("  Enter the keys again? [Y/n] ")).toLowerCase() === "n") fail("could not verify the Plaid keys.");
      env = await collectPlaidKeys(plaidEnv);
    }
  }

  // 2. Names
  let app = "";
  let region = "";
  if (fs.existsSync(FLY_TOML)) {
    const existing = appFromFlyToml(fs.readFileSync(FLY_TOML, "utf8"));
    if (existing && (await ask(`  fly.toml already targets "${existing}". Reuse it? [Y/n] `)).toLowerCase() !== "n") {
      app = existing;
      const m = /^primary_region = "([a-z]{3})"/m.exec(fs.readFileSync(FLY_TOML, "utf8"));
      region = m?.[1] ?? "";
    }
  }
  if (!app) {
    say("\n  Pick a name for the Fly app. It becomes the public address https://<name>.fly.dev, so avoid");
    say("  anything personal (no surname, no street). Lowercase letters, digits and hyphens, e.g. my-ledger.\n");
    for (;;) {
      app = await ask("  App name: ");
      if (APP_NAME_RE.test(app)) break;
      warn("3-30 characters, lowercase letters, digits and hyphens, starting and ending with a letter or digit.");
    }
    for (;;) {
      say("\n  Where should the machine run? Pick the Fly region nearest you (three letters):");
      say("    ord Chicago   iad Virginia   lax Los Angeles   sea Seattle   yyz Toronto");
      say("    lhr London    fra Frankfurt ams Amsterdam    syd Sydney     Full list: fly platform regions\n");
      region = (await ask("  Region: ")).toLowerCase();
      if (REGION_RE.test(region)) break;
      warn("Region codes are three lowercase letters.");
    }
    say("\n  A display name. It appears on the sign-in page and on Plaid's bank-linking screen. Anything you like.\n");
    const appName = (await ask('  Display name [Finance MCP]: ')) || "Finance MCP";
    fs.writeFileSync(FLY_TOML, renderFlyToml(fs.readFileSync(FLY_TEMPLATE, "utf8"), { app, region, appName, plaidEnv }));
    ok("wrote fly.toml (git-ignored)");
  }
  if (!region) {
    for (;;) {
      region = (await ask("  Region for the storage volume (three letters, e.g. ord, lax, lhr): ")).toLowerCase();
      if (REGION_RE.test(region)) break;
    }
  }
  const publicUrl = `https://${app}.fly.dev`;

  // 3. App and volume
  const appExisted = fly(["status", "-a", app], { quiet: true }).ok;
  if (appExisted) {
    ok(`app ${app} exists`);
  } else {
    const r = fly(["apps", "create", app]);
    if (!r.ok) fail(`could not create app "${app}": ${r.out.trim().split("\n").pop()}\n    (names are global on Fly; try another)`);
    ok(`created app ${app}`);
  }
  const vols = fly(["volumes", "list", "-a", app], { quiet: true });
  if (vols.ok && /\bplaid_data\b/.test(vols.out)) {
    ok("volume plaid_data exists");
  } else {
    const r = fly(["volumes", "create", "plaid_data", "--region", region, "--size", "1", "-a", app, "--yes"]);
    if (!r.ok) fail(`could not create the volume: ${r.out.trim().split("\n").pop()}`);
    ok("created 1 GB volume plaid_data");
  }

  // 4. Secrets
  let key = env.TOKEN_ENCRYPTION_KEY;
  if (appExisted) {
    // An existing app already holds encrypted Plaid tokens. Setting a different key would make
    // every linked bank unreadable, so compare hashes (never values) before touching it.
    const remote = fly(["ssh", "console", "-a", app, "-C", "node -e \"console.log(require('crypto').createHash('sha256').update(process.env.TOKEN_ENCRYPTION_KEY||'').digest('hex'))\""], { quiet: true });
    const remoteHash = remote.ok ? remote.out.trim().split("\n").pop()?.trim() ?? "" : "";
    const localHash = createHash("sha256").update(key ?? "").digest("hex");
    const emptyHash = createHash("sha256").update("").digest("hex");
    if (remote.ok && remoteHash !== emptyHash && remoteHash !== localHash) {
      fail(
        `the app already has a TOKEN_ENCRYPTION_KEY that differs from ${key ? "the one in .env" : "your .env (which has none)"}.\n` +
          "    Replacing it would make the banks already linked on the server unreadable. Either:\n" +
          `    - copy the server's key into .env first:  fly ssh console -a ${app} -C 'printenv TOKEN_ENCRYPTION_KEY'\n` +
          "      (it prints once; paste it as TOKEN_ENCRYPTION_KEY=... in .env, then rerun), or\n" +
          `    - accept relinking every bank: unlink them first with the unlink tool or \`node dist/cli.js unlink\`.`,
      );
    }
    if (remote.ok && remoteHash === localHash && key) ok("TOKEN_ENCRYPTION_KEY matches the one on the server");
    if (!remote.ok) warn("could not compare the encryption key with the server (fly ssh failed); continuing with the local one");
  }
  if (!key) {
    key = randomBytes(32).toString("base64");
    fs.writeFileSync(ENV_PATH, mergeEnv(fs.readFileSync(ENV_PATH, "utf8"), { TOKEN_ENCRYPTION_KEY: key }), { mode: 0o600 });
    ok("generated TOKEN_ENCRYPTION_KEY and saved it to .env (you need the same key locally to migrate banks)");
  } else {
    ok("using TOKEN_ENCRYPTION_KEY from .env");
  }
  say(`\n  Now a passphrase. You will type it on the sign-in page whenever Claude connects (including on`);
  say(`  your phone), and it is the only thing protecting your bank data. Two ways to get one:`);
  say(`    - press Enter and the wizard generates five random words for you, or`);
  say(`    - type your own, ${MIN_PASSPHRASE}+ characters (16+ recommended), from a password manager.`);
  say(`  Either way, save it in your password manager before continuing.\n`);
  if (appExisted) warn("this app already exists: the passphrase you enter now replaces the old one at the next deploy.");
  let passphrase = "";
  for (;;) {
    passphrase = await askHidden("  Passphrase (hidden; Enter to generate one): ");
    if (passphrase === "") {
      passphrase = generatePassphrase();
      say(`\n  Your passphrase is:   ${passphrase}\n`);
      say("  Save it now. It will not be shown again, and it cannot be recovered, only replaced by rerunning this wizard.");
      const saved = (await ask("  Type saved when it is in your password manager: ")).toLowerCase();
      if (saved !== "saved") {
        warn("not confirmed; generating a new one.");
        continue;
      }
      break;
    }
    if (passphrase.length < MIN_PASSPHRASE) {
      warn(`at least ${MIN_PASSPHRASE} characters.`);
      continue;
    }
    const again = await askHidden("  Type it again: ");
    if (again === passphrase) break;
    warn("they did not match; try again.");
  }
  // Each secret is one argv element: no shell, so no quoting can go wrong and nothing is echoed.
  const r = fly(["secrets", "set", "-a", app, "--stage", `PLAID_CLIENT_ID=${env.PLAID_CLIENT_ID}`, `PLAID_SECRET_${plaidEnv.toUpperCase()}=${secret}`, `TOKEN_ENCRYPTION_KEY=${key}`, `MCP_PASSPHRASE=${passphrase}`], { quiet: true });
  if (!r.ok) fail(`fly secrets set failed: ${r.out.trim().split("\n").pop()}`);
  ok("secrets staged: PLAID_CLIENT_ID, PLAID_SECRET_" + plaidEnv.toUpperCase() + ", TOKEN_ENCRYPTION_KEY, MCP_PASSPHRASE");

  // 5. Deploy and verify
  if (!run(`deploying ${app} (first build takes a few minutes)`, "fly", ["deploy", "-a", app, "--ha=false"])) fail("deploy failed; see the output above. Fix and run `npm run setup:hosted` again.");
  process.stdout.write("  waiting for the server to answer /health ");
  let healthy = false;
  for (let i = 0; i < 45 && !healthy; i++) {
    try {
      const res = await fetch(`${publicUrl}/health`, { signal: AbortSignal.timeout(4000) });
      healthy = res.ok;
    } catch {
      /* not up yet */
    }
    if (!healthy) {
      process.stdout.write(".");
      await new Promise((r) => setTimeout(r, 2000));
    }
  }
  say("");
  if (!healthy) fail(`the server did not answer at ${publicUrl}/health. Check \`fly logs -a ${app}\`.`);
  ok(`${publicUrl} is up`);

  say(`
  Connect Claude:

    claude.ai (web, desktop, phone): Settings → Connectors → Add custom connector
      URL: ${publicUrl}/mcp      then sign in with your passphrase

    Claude Code:
      claude mcp add --scope user --transport http ${app} ${publicUrl}/mcp
      then /mcp → authenticate

  Link a bank from any device by asking Claude for start_link, finishing in the browser, then link_status.

  Already linked banks on this laptop? Move them without re-linking:
    npm run cli -- export-items /tmp/items.json
    fly sftp shell -a ${app}        # then:  put /tmp/items.json /data/import.json
    fly machine restart -a ${app}   # imports on boot, points webhooks here, re-syncs
    rm /tmp/items.json

  Logs: fly logs -a ${app}
`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e) => fail(e instanceof Error ? e.message : String(e)));
}
