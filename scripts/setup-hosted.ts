/**
 * Guided hosted-mode deploy to Fly.io: `npm run setup:hosted`
 *
 *   1. checks the Fly CLI is installed and signed in, and that .env has Plaid keys
 *   2. asks for an app name, region and display name; writes fly.toml from the template
 *   3. creates the app and its volume (skips what already exists)
 *   4. generates TOKEN_ENCRYPTION_KEY (kept in .env too, for migrating banks later),
 *      asks for a passphrase with hidden input, and sets every secret without a shell
 *   5. deploys, waits for /health, and prints the URLs to connect Claude
 *
 * Re-runnable: existing app, volume and fly.toml are reused; secrets are re-set.
 */
import fs from "node:fs";
import path from "node:path";
import { randomBytes } from "node:crypto";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { ask, askHidden, fail, mergeEnv, ok, parseEnv, run, say, warn } from "./setup.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ENV_PATH = path.join(ROOT, ".env");
const FLY_TOML = path.join(ROOT, "fly.toml");
const FLY_TEMPLATE = path.join(ROOT, "fly.example.toml");
const APP_NAME_RE = /^[a-z0-9][a-z0-9-]{1,28}[a-z0-9]$/;
const REGION_RE = /^[a-z]{3}$/;
const MIN_PASSPHRASE = 12;

/** Fill the template with the chosen values. Pure, for tests. */
export function renderFlyToml(template: string, v: { app: string; region: string; appName: string; plaidEnv: "production" | "sandbox" }): string {
  return template
    .replace(/^# Copy to fly\.toml.*$/m, `# Generated by \`npm run setup:hosted\`; git-ignored. Edit freely and run \`fly deploy -a ${v.app} --ha=false\`.`)
    .replace(/^app = "<app>"/m, `app = "${v.app}"`)
    .replace(/^primary_region = "<region>".*$/m, `primary_region = "${v.region}"`)
    .replace(/PUBLIC_URL = "https:\/\/<app>\.fly\.dev"/, `PUBLIC_URL = "https://${v.app}.fly.dev"`)
    .replace(/^(\s*)APP_NAME = ".*?"(.*)$/m, `$1APP_NAME = "${v.appName.replace(/"/g, "")}"$2`)
    .replace(/^(\s*)PLAID_ENV = ".*?"(.*)$/m, `$1PLAID_ENV = "${v.plaidEnv}"$2`);
}

/** Read the app name back out of an existing fly.toml. Pure, for tests. */
export function appFromFlyToml(toml: string): string | null {
  const m = /^app = "([^"]+)"/m.exec(toml);
  return m && m[1] !== "<app>" ? m[1] : null;
}

function fly(args: string[], opts: { quiet?: boolean } = {}): { ok: boolean; out: string } {
  const r = spawnSync("fly", args, { cwd: ROOT, encoding: "utf8", stdio: opts.quiet ? ["ignore", "pipe", "pipe"] : ["inherit", "pipe", "pipe"] });
  return { ok: r.status === 0, out: `${r.stdout ?? ""}${r.stderr ?? ""}` };
}

async function main() {
  say("\nplaid-finance-mcp hosted setup (Fly.io)\n");
  if (!process.stdin.isTTY) fail("Run this in an interactive terminal.");

  // 1. Prerequisites
  if (!fly(["version"], { quiet: true }).ok) fail("The Fly CLI is not installed. See https://fly.io/docs/flyctl/install/ then run `fly auth login`.");
  ok("Fly CLI installed");
  if (!fly(["auth", "whoami"], { quiet: true }).ok) fail("Not signed in to Fly. Run `fly auth login` and try again.");
  ok("signed in to Fly");
  if (!fs.existsSync(ENV_PATH)) fail("No .env yet. Run `npm run setup` first.");
  const env = parseEnv(fs.readFileSync(ENV_PATH, "utf8"));
  if (!env.PLAID_CLIENT_ID) fail("PLAID_CLIENT_ID is missing from .env. Run `npm run setup` first.");

  const plaidEnvAnswer = (await ask("  Plaid environment for the server [production/sandbox] (production): ")).toLowerCase() || "production";
  if (plaidEnvAnswer !== "production" && plaidEnvAnswer !== "sandbox") fail("Answer production or sandbox.");
  const plaidEnv = plaidEnvAnswer as "production" | "sandbox";
  const secret = plaidEnv === "production" ? env.PLAID_SECRET_PRODUCTION || env.PLAID_SECRET : env.PLAID_SECRET_SANDBOX || env.PLAID_SECRET;
  if (!secret) fail(`No ${plaidEnv} secret in .env (PLAID_SECRET_${plaidEnv.toUpperCase()}). Run \`npm run setup\` and add it.`);
  ok(`Plaid keys for ${plaidEnv} found in .env`);

  // 2. Names
  let app = "";
  let region = "";
  if (fs.existsSync(FLY_TOML)) {
    const existing = appFromFlyToml(fs.readFileSync(FLY_TOML, "utf8"));
    if (existing && (await ask(`  fly.toml already targets "${existing}". Reuse it? [Y/n] `)).toLowerCase() !== "n") {
      app = existing;
      const m = /^primary_region = "([a-z]{3})"/m.exec(fs.readFileSync(FLY_TOML, "utf8"));
      region = m?.[1] ?? "";
    }
  }
  if (!app) {
    say("\n  Pick a name for the Fly app. It becomes the public hostname <name>.fly.dev, so avoid anything");
    say("  personal (no surname, no street). Lowercase letters, digits and hyphens.\n");
    for (;;) {
      app = await ask("  app name: ");
      if (APP_NAME_RE.test(app)) break;
      warn("3-30 characters, lowercase letters, digits and hyphens, starting and ending with a letter or digit.");
    }
    for (;;) {
      region = (await ask("  region code (e.g. ord Chicago, lax Los Angeles, lhr London, fra Frankfurt; `fly platform regions` lists all): ")).toLowerCase();
      if (REGION_RE.test(region)) break;
      warn("Region codes are three lowercase letters.");
    }
    const appName = (await ask('  display name shown on the sign-in page and Plaid\'s Link screen (Finance MCP): ')) || "Finance MCP";
    fs.writeFileSync(FLY_TOML, renderFlyToml(fs.readFileSync(FLY_TEMPLATE, "utf8"), { app, region, appName, plaidEnv }));
    ok("wrote fly.toml (git-ignored)");
  }
  if (!region) {
    for (;;) {
      region = (await ask("  region code for the volume (e.g. ord, lax, lhr, fra): ")).toLowerCase();
      if (REGION_RE.test(region)) break;
    }
  }
  const publicUrl = `https://${app}.fly.dev`;

  // 3. App and volume
  const appExisted = fly(["status", "-a", app], { quiet: true }).ok;
  if (appExisted) {
    ok(`app ${app} exists`);
  } else {
    const r = fly(["apps", "create", app]);
    if (!r.ok) fail(`could not create app "${app}": ${r.out.trim().split("\n").pop()}\n    (names are global on Fly; try another)`);
    ok(`created app ${app}`);
  }
  const vols = fly(["volumes", "list", "-a", app], { quiet: true });
  if (vols.ok && /\bplaid_data\b/.test(vols.out)) {
    ok("volume plaid_data exists");
  } else {
    const r = fly(["volumes", "create", "plaid_data", "--region", region, "--size", "1", "-a", app, "--yes"]);
    if (!r.ok) fail(`could not create the volume: ${r.out.trim().split("\n").pop()}`);
    ok("created 1 GB volume plaid_data");
  }

  // 4. Secrets
  let key = env.TOKEN_ENCRYPTION_KEY;
  if (!key) {
    key = randomBytes(32).toString("base64");
    fs.writeFileSync(ENV_PATH, mergeEnv(fs.readFileSync(ENV_PATH, "utf8"), { TOKEN_ENCRYPTION_KEY: key }), { mode: 0o600 });
    ok("generated TOKEN_ENCRYPTION_KEY and saved it to .env (you need the same key locally to migrate banks)");
  } else {
    ok("using TOKEN_ENCRYPTION_KEY from .env");
  }
  say(`\n  Choose the passphrase you will type when Claude asks to connect. It is the only credential`);
  say(`  protecting your bank data, so make it long (${MIN_PASSPHRASE}+ characters, 16+ recommended). Typing is hidden.\n`);
  if (appExisted) warn("this app already exists: the passphrase you enter now replaces the old one at the next deploy.");
  let passphrase = "";
  for (;;) {
    passphrase = await askHidden("  passphrase: ");
    if (passphrase.length < MIN_PASSPHRASE) {
      warn(`at least ${MIN_PASSPHRASE} characters.`);
      continue;
    }
    const again = await askHidden("  again: ");
    if (again === passphrase) break;
    warn("they did not match; try again.");
  }
  // Each secret is one argv element: no shell, so no quoting can go wrong and nothing is echoed.
  const r = fly(["secrets", "set", "-a", app, "--stage", `PLAID_CLIENT_ID=${env.PLAID_CLIENT_ID}`, `PLAID_SECRET_${plaidEnv.toUpperCase()}=${secret}`, `TOKEN_ENCRYPTION_KEY=${key}`, `MCP_PASSPHRASE=${passphrase}`], { quiet: true });
  if (!r.ok) fail(`fly secrets set failed: ${r.out.trim().split("\n").pop()}`);
  ok("secrets staged: PLAID_CLIENT_ID, PLAID_SECRET_" + plaidEnv.toUpperCase() + ", TOKEN_ENCRYPTION_KEY, MCP_PASSPHRASE");

  // 5. Deploy and verify
  if (!run(`deploying ${app} (first build takes a few minutes)`, "fly", ["deploy", "-a", app, "--ha=false"])) fail("deploy failed; see the output above. Fix and run `npm run setup:hosted` again.");
  process.stdout.write("  waiting for the server to answer /health ");
  let healthy = false;
  for (let i = 0; i < 45 && !healthy; i++) {
    try {
      const res = await fetch(`${publicUrl}/health`, { signal: AbortSignal.timeout(4000) });
      healthy = res.ok;
    } catch {
      /* not up yet */
    }
    if (!healthy) {
      process.stdout.write(".");
      await new Promise((r) => setTimeout(r, 2000));
    }
  }
  say("");
  if (!healthy) fail(`the server did not answer at ${publicUrl}/health. Check \`fly logs -a ${app}\`.`);
  ok(`${publicUrl} is up`);

  say(`
  Connect Claude:

    claude.ai (web, desktop, phone): Settings → Connectors → Add custom connector
      URL: ${publicUrl}/mcp      then sign in with your passphrase

    Claude Code:
      claude mcp add --scope user --transport http ${app} ${publicUrl}/mcp
      then /mcp → authenticate

  Link a bank from any device by asking Claude for start_link, finishing in the browser, then link_status.

  Already linked banks on this laptop? Move them without re-linking:
    npm run cli -- export-items /tmp/items.json
    fly sftp shell -a ${app}        # then:  put /tmp/items.json /data/import.json
    fly machine restart -a ${app}   # imports on boot, points webhooks here, re-syncs
    rm /tmp/items.json

  Logs: fly logs -a ${app}
`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e) => fail(e instanceof Error ? e.message : String(e)));
}
